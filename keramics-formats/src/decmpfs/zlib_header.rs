use keramics_core::ErrorTrace;
use keramics_layout_map::LayoutMap;
use keramics_types::bytes_to_u32_be;

#[derive(Debug, LayoutMap)]
#[layout_map(
    structure(
        byte_order = "big",
        field(name = "unknown1", data_type = "u32", format = "hex"),
        field(name = "footer_offset", data_type = "u32", format = "hex"),
        field(name = "unknown2", data_type = "u32"),
        field(name = "footer_size", data_type = "u32"),
        field(name = "unknown3", data_type = "[u8; 240]"),
        field(name = "unknown4", data_type = "u32"),
    ),
    methods("debug_read_data", "read_at_position")
)]
/// Apple File System Compression (decmpfs) zlib (compressed) header.
pub struct DecmpfsZlibHeader {
    /// Footer offset.
    pub footer_offset: u32,

    /// Footer size.
    pub footer_size: u32,
}

impl DecmpfsZlibHeader {
    /// Creates a new header.
    pub fn new() -> Self {
        Self {
            footer_offset: 0,
            footer_size: 0,
        }
    }

    /// Reads the fork descriptor from a buffer.
    pub fn read_data(&mut self, data: &[u8]) -> Result<(), ErrorTrace> {
        if data.len() < 260 {
            return Err(keramics_core::error_trace_new!("Unsupported data size"));
        }
        self.footer_offset = bytes_to_u32_be!(data, 4);
        self.footer_size = bytes_to_u32_be!(data, 12);

        Ok(())
    }
}

