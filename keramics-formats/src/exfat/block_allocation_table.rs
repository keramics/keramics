use std::io::SeekFrom;

use keramics_core::{DataStreamReference, DebugTrace, ErrorTrace};
use keramics_types::bytes_to_u32_le;

/// Extensible File Allocation Table (exFAT) cluster block allocation table.
pub struct ExFatBlockAllocationTable {
    /// Offset.
    offset: u64,

    /// Number of entries.
    number_of_entries: u32,

    /// First cluster offset.
    pub first_cluster_offset: u64,

    /// Cluster block size.
    pub cluster_block_size: u32,
}

impl ExFatBlockAllocationTable {
    /// Creates a new block allocation table.
    pub fn new(
        offset: u64,
        number_of_entries: u32,
        first_cluster_offset: u64,
        cluster_block_size: u32,
    ) -> Self {
        Self {
            offset,
            number_of_entries,
            first_cluster_offset,
            cluster_block_size,
        }
    }

    /// Reads a block allocation table entry.
    pub fn read_entry(
        &self,
        data_stream: &DataStreamReference,
        entry_index: u32,
    ) -> Result<u32, ErrorTrace> {
        if entry_index >= self.number_of_entries {
            return Err(keramics_core::error_trace_new!(format!(
                "Unsupported entry index: {} value out of bounds",
                entry_index
            )));
        }
        let entry_offset: u64 = self.offset + ((entry_index as u64) * 4);

        let mut data: Vec<u8> = vec![0; 4];

        keramics_core::data_stream_read_exact_at_position!(
            data_stream,
            &mut data,
            SeekFrom::Start(entry_offset)
        );
        let entry: u32 = bytes_to_u32_le!(data, 0);
        println!("X: 0x{:08x}, {}, {}", entry_offset, entry_index, entry);

        DebugTrace::static_scope(|debug_trace| {
            debug_trace.print_start("ExFatBlockAllocationTableEntry");
            debug_trace.print_field("entry_index", entry_index);
            debug_trace.print_field(
                "entry_offset",
                format!("{} (0x{:x})", entry_offset, entry_offset),
            );
            debug_trace.print_field("cluster_block_number", entry);
            debug_trace.print_end();
        });
        Ok(entry)
    }
}

