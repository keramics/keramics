use keramics_core::ErrorTrace;
use keramics_layout_map::LayoutMap;
use keramics_types::bytes_to_u32_le;

use super::checkpoint_map_entry::ApfsCheckpointMapEntry;
use super::object_checksum::ApfsObjectChecksum;
use super::object_header::ApfsObjectHeader;

#[derive(LayoutMap)]
#[layout_map(
    structure(
        byte_order = "little",
        field(name = "object_header", data_type = "Struct<ApfsObjectHeader; 32>"),
        field(name = "flags", data_type = "u32", format = "hex"),
        field(name = "number_of_entries", data_type = "u32"),
        field(
            name = "entries",
            data_type = "[Struct<ApfsCheckpointMapEntry; 40>; 101]"
        ),
        field(name = "unknown1", data_type = "[u8; 16]"),
    ),
    methods("debug_read_data", "read_at_position")
)]
/// Apple File System (APFS) checkpoint map.
pub struct ApfsCheckpointMap {
    /// Object header.
    pub object_header: ApfsObjectHeader,

    /// Flags.
    pub flags: u32,

    /// Entries.
    pub entries: Vec<ApfsCheckpointMapEntry>,
}

impl ApfsCheckpointMap {
    /// Creates a new checkpoint map.
    pub fn new() -> Self {
        Self {
            object_header: ApfsObjectHeader::new(),
            flags: 0,
            entries: Vec::new(),
        }
    }

    /// Reads the checkpoint map from a buffer.
    pub fn read_data(&mut self, data: &[u8]) -> Result<(), ErrorTrace> {
        if data.len() < 4096 {
            return Err(keramics_core::error_trace_new!("Unsupported data size"));
        }
        match self.object_header.read_data(&data) {
            Ok(_) => {}
            Err(mut error) => {
                keramics_core::error_trace_add_frame!(error, "Unable to read object header");
                return Err(error);
            }
        }
        if self.object_header.object_type != 0x4000000c {
            return Err(keramics_core::error_trace_new!("Unsupported object type"));
        }
        if self.object_header.object_subtype != 0x00000000 {
            return Err(keramics_core::error_trace_new!(
                "Unsupported object subtype"
            ));
        }
        if self.object_header.checksum != 0 {
            let calculated_checksum: u64 = ApfsObjectChecksum::calculate(&data[8..4096]);

            if self.object_header.checksum != calculated_checksum {
                return Err(keramics_core::error_trace_new!(format!(
                    "Mismatch between stored: 0x{:016x} and calculated: 0x{:016x} checksums",
                    self.object_header.checksum, calculated_checksum
                )));
            }
        }
        self.flags = bytes_to_u32_le!(data, 32);

        let number_of_entries: u32 = bytes_to_u32_le!(data, 36);

        if number_of_entries > 101 {
            return Err(keramics_core::error_trace_new!(format!(
                "Invalid number of entries: {} value out of bounds",
                number_of_entries
            )));
        }
        let mut data_offset: usize = 40;

        for entry_index in 0..number_of_entries {
            let mut entry: ApfsCheckpointMapEntry = ApfsCheckpointMapEntry::new();

            match entry.read_data(&data[data_offset..]) {
                Ok(_) => {}
                Err(mut error) => {
                    keramics_core::error_trace_add_frame!(
                        error,
                        format!("Unable to read entry: {}", entry_index)
                    );
                    return Err(error);
                }
            }
            data_offset += 40;

            self.entries.push(entry);
        }
        Ok(())
    }
}

