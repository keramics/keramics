    fn test_read_data() -> Result<(), ErrorTrace> {
        let test_data: Vec<u8> = get_test_data();

        let mut test_struct = ApfsCheckpointMap::new();
        test_struct.read_data(&test_data)?;

        assert_eq!(test_struct.object_header.checksum, 0x8139fd683ec5b1e7);
        assert_eq!(test_struct.object_header.identifier, 1);
        assert_eq!(test_struct.object_header.transaction_identifier, 5);
        assert_eq!(test_struct.object_header.object_type, 0x4000000c);
        assert_eq!(test_struct.object_header.object_subtype, 0x00000000);
        assert_eq!(test_struct.flags, 0x00000001);
        assert_eq!(test_struct.entries.len(), 4);

        Ok(())
    }

