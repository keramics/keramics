    #[test]
    fn test_read_data() -> Result<(), ErrorTrace> {
        let test_data: Vec<u8> = get_test_data();

        let mut test_struct = ApfsBtreeNode::new();
        test_struct.read_data(&test_data)?;

        assert_eq!(test_struct.object_header.checksum, 0x91e4afbe1e5919bf);
        assert_eq!(test_struct.object_header.identifier, 149);
        assert_eq!(test_struct.object_header.transaction_identifier, 6);
        assert_eq!(test_struct.object_header.object_type, 0x40000002);
        assert_eq!(test_struct.object_header.object_subtype, 0x0000000b);
        assert_eq!(test_struct.node_header.flags, 0x0007);

        Ok(())
    }

    #[test]
    fn test_read_data_with_unsupported_data_size() {
        let mut test_struct = ApfsBtreeNode::new();

        let test_data: Vec<u8> = get_test_data();
        let result = test_struct.read_data(&test_data[0..55]);
        assert!(result.is_err());

        let test_data: Vec<u8> = get_test_data();
        let result = test_struct.read_data(&test_data[0..95]);
        assert!(result.is_err());
    }

    #[test]
    fn test_read_data_with_checksum_mismatch() {
        let mut test_data: Vec<u8> = get_test_data();
        test_data[0] = 0xff;

        let mut test_struct = ApfsBtreeNode::new();
        let result = test_struct.read_data(&test_data);
        assert!(result.is_err());
    }

