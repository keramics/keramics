use super::btree_entry::ApfsBtreeEntry;
use super::btree_entry_fixed_size::ApfsBtreeEntryFixedSize;
use super::btree_entry_variable_size::ApfsBtreeEntryVariableSize;
use super::btree_footer::ApfsBtreeFooter;
use super::btree_node_header::ApfsBtreeNodeHeader;
use super::object_checksum::ApfsObjectChecksum;
use super::object_header::ApfsObjectHeader;

/// Apple File System (APFS) B-tree node.
pub struct ApfsBtreeNode {
    /// Object header.
    pub object_header: ApfsObjectHeader,

    /// Node header.
    pub node_header: ApfsBtreeNodeHeader,

    /// Footer.
    pub footer: Option<ApfsBtreeFooter>,

    /// Data.
    data: Vec<u8>,

    /// Entries.
    pub entries: Vec<ApfsBtreeEntry>,
}

impl ApfsBtreeNode {
    /// Creates a new B-tree node.
    pub fn new() -> Self {
        Self {
            object_header: ApfsObjectHeader::new(),
            node_header: ApfsBtreeNodeHeader::new(),
            footer: None,
            data: Vec::new(),
            entries: Vec::new(),
        }
    }

    /// Retrieves the key data of a specific entry.
    pub fn get_key_data_by_index(&self, entry_index: usize) -> Option<&[u8]> {
        match self.entries.get(entry_index) {
            Some(entry) => {
                let data_end_offset: usize = entry.key_data_offset + entry.key_data_size;

                let key_data: &[u8] = &self.data[entry.key_data_offset..data_end_offset];

                keramics_core::debug_trace_data!(
                    format!("ApfsBtreeEntryKey: {}", entry_index),
                    entry.key_data_offset,
                    key_data,
                    entry.key_data_size
                );
                Some(&key_data)
            }
            None => None,
        }
    }

    /// Retrieves the value data of a specific entry.
    pub fn get_value_data_by_index(&self, entry_index: usize) -> Option<&[u8]> {
        match self.entries.get(entry_index) {
            Some(entry) => {
                let data_end_offset: usize = entry.value_data_offset + entry.value_data_size;

                let value_data: &[u8] = &self.data[entry.value_data_offset..data_end_offset];

                keramics_core::debug_trace_data!(
                    format!("ApfsBtreeEntryValue: {}", entry_index),
                    entry.value_data_offset,
                    value_data,
                    entry.value_data_size
                );
                Some(&value_data)
            }
            None => None,
        }
    }

    /// Determines if the node is a branch node.
    pub fn is_branch(&self) -> bool {
        self.node_header.flags & 0x0002 == 0
    }

    /// Determines if the node is a root node.
    pub fn is_root(&self) -> bool {
        self.node_header.flags & 0x0001 != 0
    }

    /// Reads the B-tree node from a buffer.
    pub fn read_data(&mut self, data: &[u8]) -> Result<(), ErrorTrace> {
        let data_size: usize = data.len();

        if data_size < 56 {
            return Err(keramics_core::error_trace_new!("Unsupported data size"));
        }
        keramics_core::debug_trace_structure!(ApfsObjectHeader::debug_read_data(data));

        match self.object_header.read_data(&data) {
            Ok(_) => {}
            Err(mut error) => {
                keramics_core::error_trace_add_frame!(error, "Unable to read object header");
                return Err(error);
            }
        }
        let calculated_checksum: u64 = ApfsObjectChecksum::calculate(&data[8..]);

        if self.object_header.checksum != calculated_checksum {
            return Err(keramics_core::error_trace_new!(format!(
                "Mismatch between stored: 0x{:016x} and calculated: 0x{:016x} checksums",
                self.object_header.checksum, calculated_checksum
            )));
        }
        let mut data_offset: usize = 32;
        let mut data_end_offset: usize = data_size;

        keramics_core::debug_trace_structure!(ApfsBtreeNodeHeader::debug_read_data(
            &data[data_offset..]
        ));
        match self.node_header.read_data(&data[data_offset..]) {
            Ok(_) => {}
            Err(mut error) => {
                keramics_core::error_trace_add_frame!(error, "Unable to read node header");
                return Err(error);
            }
        }
        data_offset += 24;

        if self.is_root() {
            if data_size - data_offset < 40 {
                return Err(keramics_core::error_trace_new!(
                    "Unsupported footer offset value out of bounds"
                ));
            }
            data_end_offset -= 40;

            keramics_core::debug_trace_structure!(ApfsBtreeFooter::debug_read_data(
                &data[data_end_offset..]
            ));
            let mut footer: ApfsBtreeFooter = ApfsBtreeFooter::new();

            match footer.read_data(&data[data_end_offset..]) {
                Ok(_) => {}
                Err(mut error) => {
                    keramics_core::error_trace_add_frame!(error, "Unable to read footer");
                    return Err(error);
                }
            }
            self.footer = Some(footer);
        }
        if (self.node_header.entries_data_offset as usize) > data_end_offset - data_offset {
            return Err(keramics_core::error_trace_new!(
                "Unsupported entries data offset value out of bounds"
            ));
        }
        let entries_data_offset: usize =
            data_offset + (self.node_header.entries_data_offset as usize);

        if (self.node_header.entries_data_size as usize) > data_end_offset - entries_data_offset {
            return Err(keramics_core::error_trace_new!(
                "Unsupported entries data size value out of bounds"
            ));
        }
        let keys_data_offset: usize =
            entries_data_offset + (self.node_header.entries_data_size as usize);

        let entry_size: usize = if self.node_header.flags & 0x0004 == 0 {
            8
        } else {
            4
        };
        if (self.node_header.number_of_keys as usize)
            > (self.node_header.entries_data_size as usize) / entry_size
        {
            return Err(keramics_core::error_trace_new!(
                "Unsupported number of keys value out of bounds"
            ));
        }
        data_offset = entries_data_offset;

        for entry_index in 0..self.node_header.number_of_keys {
            let mut entry: ApfsBtreeEntry = ApfsBtreeEntry::new();

            if self.node_header.flags & 0x0004 == 0 {
                keramics_core::debug_trace_structure!(ApfsBtreeEntryVariableSize::debug_read_data(
                    &data[data_offset..]
                ));
                match ApfsBtreeEntryVariableSize::read_data(&mut entry, &data[data_offset..]) {
                    Ok(_) => {}
                    Err(mut error) => {
                        keramics_core::error_trace_add_frame!(
                            error,
                            format!("Unable to read variable size entry: {}", entry_index)
                        );
                        return Err(error);
                    }
                }
            } else {
                keramics_core::debug_trace_structure!(ApfsBtreeEntryFixedSize::debug_read_data(
                    &data[data_offset..]
                ));
                match ApfsBtreeEntryFixedSize::read_data(&mut entry, &data[data_offset..]) {
                    Ok(_) => {}
                    Err(mut error) => {
                        keramics_core::error_trace_add_frame!(
                            error,
                            format!("Unable to read fixed size entry: {}", entry_index)
                        );
                        return Err(error);
                    }
                }
                match self.object_header.object_subtype {
                    0x0000000b => {
                        entry.key_data_size = 16;
                        entry.value_data_size = 16;
                    }
                    _ => {
                        return Err(keramics_core::error_trace_new!(format!(
                            "Unsupported object subtype: 0x{:08x}",
                            self.object_header.object_subtype
                        )));
                    }
                }
                if self.is_branch() {
                    entry.value_data_size = 8;
                }
            }
            if entry.value_data_offset > data_end_offset {
                return Err(keramics_core::error_trace_new!(format!(
                    "Invalid entry: {} - value data offset value out of bounds",
                    entry_index
                )));
            }
            entry.key_data_offset += keys_data_offset;
            entry.value_data_offset = data_end_offset - entry.value_data_offset;

            if entry.key_data_size > data_end_offset - entry.key_data_offset {
                return Err(keramics_core::error_trace_new!(format!(
                    "Invalid entry: {} - key data size value out of bounds",
                    entry_index
                )));
            }
            if entry.value_data_size > data_end_offset - entry.value_data_offset {
                return Err(keramics_core::error_trace_new!(format!(
                    "Invalid entry: {} - value data size value out of bounds",
                    entry_index
                )));
            }
            self.entries.push(entry);

            data_offset += entry_size;
        }
        Ok(())
    }

    /// Reads the B-tree node from a specific position in a data stream.
    pub fn read_at_position(
        &mut self,
        data_stream: &DataStreamReference,
        position: SeekFrom,
    ) -> Result<(), ErrorTrace> {
        let mut data: Vec<u8> = vec![0; 4096];

        let offset: u64 =
            keramics_core::data_stream_read_exact_at_position!(data_stream, &mut data, position);

        keramics_core::debug_trace_data!("ApfsBtreeNode", offset, &data, data.len());

        match self.read_data(&data) {
            Ok(_) => {}
            Err(mut error) => {
                keramics_core::error_trace_add_frame!(error, "Unable to read B-tree node data");
                return Err(error);
            }
        }
        self.data = data;

        Ok(())
    }
}

