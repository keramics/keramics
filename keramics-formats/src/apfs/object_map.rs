use super::object_checksum::ApfsObjectChecksum;
use super::object_header::ApfsObjectHeader;

#[derive(LayoutMap)]
#[layout_map(
    structure(
        byte_order = "little",
        field(name = "object_header", data_type = "Struct<ApfsObjectHeader; 32>"),
        field(name = "flags", data_type = "u32", format = "hex"),
        field(name = "number_of_snapshots", data_type = "u32"),
        field(name = "btree_type", data_type = "u32", format = "hex"),
        field(name = "snaphots_btree_type", data_type = "u32", format = "hex"),
        field(name = "btree_block_number", data_type = "u64"),
        field(name = "snapshots_btree_block_number", data_type = "u64"),
        field(name = "most_recent_snapshot_identifier", data_type = "u64"),
        field(name = "unknown1", data_type = "u64"),
        field(name = "unknown2", data_type = "u64"),
        field(name = "unknown3", data_type = "[u8; 4008]"),
    ),
    methods("debug_read_data", "read_at_position")
)]
/// Apple File System (APFS) object map.
pub struct ApfsObjectMap {
    /// Object header.
    pub object_header: ApfsObjectHeader,

    /// Flags.
    pub flags: u32,

    /// Number of snaphots.
    pub number_of_snapshots: u32,

    /// B-tree block number.
    pub btree_block_number: u64,
}

impl ApfsObjectMap {
    /// Creates a new object map.
    pub fn new() -> Self {
        Self {
            object_header: ApfsObjectHeader::new(),
            flags: 0,
            number_of_snapshots: 0,
            btree_block_number: 0,
        }
    }

    /// Reads the object map from a buffer.
    pub fn read_data(&mut self, data: &[u8]) -> Result<(), ErrorTrace> {
        if data.len() < 4096 {
            return Err(keramics_core::error_trace_new!("Unsupported data size"));
        }
        match self.object_header.read_data(&data) {
            Ok(_) => {}
            Err(mut error) => {
                keramics_core::error_trace_add_frame!(error, "Unable to read object header");
                return Err(error);
            }
        }
        if self.object_header.object_type != 0x4000000b {
            return Err(keramics_core::error_trace_new!("Unsupported object type"));
        }
        if self.object_header.object_subtype != 0x00000000 {
            return Err(keramics_core::error_trace_new!(
                "Unsupported object subtype"
            ));
        }
        let calculated_checksum: u64 = ApfsObjectChecksum::calculate(&data[8..4096]);

        if self.object_header.checksum != calculated_checksum {
            return Err(keramics_core::error_trace_new!(format!(
                "Mismatch between stored: 0x{:016x} and calculated: 0x{:016x} checksums",
                self.object_header.checksum, calculated_checksum
            )));
        }
        self.flags = bytes_to_u32_le!(data, 32);
        self.number_of_snapshots = bytes_to_u32_le!(data, 36);
        self.btree_block_number = bytes_to_u64_le!(data, 48);

        Ok(())
    }
}

