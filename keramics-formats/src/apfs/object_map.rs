    fn test_read_data() -> Result<(), ErrorTrace> {
        let test_data: Vec<u8> = get_test_data();

        let mut test_struct = ApfsObjectMap::new();
        test_struct.read_data(&test_data)?;

        assert_eq!(test_struct.object_header.checksum, 0x4004f649fffb0876);
        assert_eq!(test_struct.object_header.identifier, 148);
        assert_eq!(test_struct.object_header.transaction_identifier, 6);
        assert_eq!(test_struct.object_header.object_type, 0x4000000b);
        assert_eq!(test_struct.object_header.object_subtype, 0x00000000);
        assert_eq!(test_struct.flags, 0x00000001);
        assert_eq!(test_struct.number_of_snapshots, 0);
        assert_eq!(test_struct.btree_block_number, 149);

        Ok(())
    }

