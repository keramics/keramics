/// Apple File System (APFS) key bag.
pub struct ApfsKeyBag {
    /// Bytest per sector.
    bytes_per_sector: u16,

    /// Key.
    key: Vec<u8>,

    /// Tweak key.
    tweak_key: Vec<u8>,

    /// Value to indicate the key bag is locked.
    pub is_locked: bool,

    /// Object header.
    pub object_header: ApfsObjectHeader,

    /// Entries.
    entries: Vec<ApfsKeyBagEntry>,
}

impl ApfsKeyBag {
    /// Creates a new key bag.
    pub fn new(bytes_per_sector: u16, key: &[u8], tweak_key: &[u8]) -> Self {
        Self {
            bytes_per_sector,
            key: key.to_vec(),
            tweak_key: tweak_key.to_vec(),
            is_locked: true,
            object_header: ApfsObjectHeader::new(),
            entries: Vec::new(),
        }
    }

    /// Retrieves a specific entry.
    pub fn get_entry(&self, identifier: &Uuid, entry_type: u16) -> Option<&[u8]> {
        for entry in self.entries.iter() {
            if &entry.identifier == identifier && entry.entry_type == entry_type {
                return Some(&entry.data);
            }
        }
        None
    }

    /// Reads the key bag from a buffer.
    pub fn read_data(&mut self, data: &[u8]) -> Result<(), ErrorTrace> {
        let data_size: usize = data.len();

        if data_size < 48 {
            return Err(keramics_core::error_trace_new!("Unsupported data size"));
        }
        keramics_core::debug_trace_structure!(ApfsObjectHeader::debug_read_data(data));

        match self.object_header.read_data(&data) {
            Ok(_) => {}
            Err(mut error) => {
                keramics_core::error_trace_add_frame!(error, "Unable to read object header");
                return Err(error);
            }
        }
        if self.object_header.object_type != 0x6b657973
            && self.object_header.object_type != 0x72656373
        {
            return Err(keramics_core::error_trace_new!("Unsupported object type"));
        }
        if self.object_header.object_subtype != 0x00000000 {
            return Err(keramics_core::error_trace_new!(
                "Unsupported object subtype"
            ));
        }
        let calculated_checksum: u64 = ApfsObjectChecksum::calculate(&data[8..]);

        if self.object_header.checksum != calculated_checksum {
            return Err(keramics_core::error_trace_new!(format!(
                "Mismatch between stored: 0x{:016x} and calculated: 0x{:016x} checksums",
                self.object_header.checksum, calculated_checksum
            )));
        }
        keramics_core::debug_trace_structure!(ApfsKeyBagHeader::debug_read_data(&data[32..]));

        let mut key_bag_header: ApfsKeyBagHeader = ApfsKeyBagHeader::new();

        match key_bag_header.read_data(&data[32..]) {
            Ok(_) => {}
            Err(mut error) => {
                keramics_core::error_trace_add_frame!(error, "Unable to read key bag header");
                return Err(error);
            }
        }
        if key_bag_header.format_version != 2 {
            return Err(keramics_core::error_trace_new!(format!(
                "Unsupported key bag format version: {}",
                key_bag_header.format_version
            )));
        }
        let mut data_offset: usize = 48;

        for entry_index in 0..key_bag_header.number_of_entries {
            if data_offset > data_size - 24 {
                return Err(keramics_core::error_trace_new!(format!(
                    "Invalid entry: {} value out of bounds",
                    entry_index
                )));
            }
            keramics_core::debug_trace_structure!(ApfsKeyBagEntry::debug_read_data(
                &data[data_offset..]
            ));
            let mut key_bag_entry: ApfsKeyBagEntry = ApfsKeyBagEntry::new();

            match key_bag_entry.read_data(&data[data_offset..]) {
                Ok(_) => {}
                Err(mut error) => {
                    keramics_core::error_trace_add_frame!(
                        error,
                        format!("Unable to read key bag entry: {}", entry_index)
                    );
                    return Err(error);
                }
            }
            data_offset += 24;

            if (key_bag_entry.data_size as usize) > data_size - data_offset {
                return Err(keramics_core::error_trace_new!(format!(
                    "Invalid entry: {} data size value out of bounds",
                    entry_index
                )));
            }
            data_offset += key_bag_entry.data_size as usize;

            self.entries.push(key_bag_entry);

            let alignment_padding: usize = calculate_alignment_padding(data_offset, 16);

            if alignment_padding > 0 {
                // TODO: debug print alignment padding.
                data_offset += alignment_padding;
            }
        }
        Ok(())
    }

    /// Reads the key bag from a specific position in a data stream.
    pub fn read_at_position(
        &mut self,
        data_stream: &DataStreamReference,
        data_size: u64,
        position: SeekFrom,
    ) -> Result<(), ErrorTrace> {
        // Note that 65536 is an arbitrary chosen limit.
        if data_size < 48 || data_size > 65536 {
            return Err(keramics_core::error_trace_new!(
                "Invalid key bag size value out of bounds"
            ));
        }
        let mut encrypted_data: Vec<u8> = vec![0; data_size as usize];

        let offset: u64 = keramics_core::data_stream_read_exact_at_position!(
            data_stream,
            &mut encrypted_data,
            position,
        );
        let mut aes_context: AesXtsContext = AesXtsContext::new();

        match aes_context.set_keys(&self.key, &self.tweak_key) {
            Ok(_) => {}
            Err(mut error) => {
                keramics_core::error_trace_add_frame!(
                    error,
                    "Unable to set keys in encryption context",
                );
                return Err(error);
            }
        }
        let first_sector: usize = (offset as usize) / (self.bytes_per_sector as usize);
        let last_sector: usize =
            first_sector + ((data_size as usize) / (self.bytes_per_sector as usize));
        let mut tweak_value: Vec<u8> = vec![0; 16];

        let mut data: Vec<u8> = vec![0; data_size as usize];
        let mut data_offset: usize = 0;

        for sector_number in first_sector..last_sector {
            tweak_value[0..8].copy_from_slice(&sector_number.to_le_bytes());

            let data_end_offset: usize = data_offset + (self.bytes_per_sector as usize);

            match aes_context.decrypt_xts(
                &tweak_value,
                &encrypted_data[data_offset..data_end_offset],
                &mut data[data_offset..data_end_offset],
            ) {
                Ok(_) => {}
                Err(mut error) => {
                    keramics_core::error_trace_add_frame!(
                        error,
                        format!("Unable to decrypt sector: {}", sector_number)
                    );
                    return Err(error);
                }
            }
            data_offset = data_end_offset;
        }
        keramics_core::debug_trace_data!("ApfsKeyBag", offset, &data, data.len());

        if &data[24..32] == APFS_CONTAINER_KEY_BAG_SIGNATURE
            || &data[24..32] == APFS_VOLUME_KEY_BAG_SIGNATURE
        {
            match self.read_data(&data) {
                Ok(_) => {}
                Err(mut error) => {
                    keramics_core::error_trace_add_frame!(error, "Unable to read key bag data");
                    return Err(error);
                }
            }
            self.is_locked = false;
        }
        Ok(())
    }
}

