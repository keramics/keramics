/// Apple File System (APFS) container superblock.
pub struct ApfsContainerSuperblock {
    /// Object header.
    pub object_header: ApfsObjectHeader,

    /// Block size.
    pub block_size: u32,

    /// Number of blocks.
    pub number_of_blocks: u64,

    /// Features flags.
    pub feature_flags: u64,

    /// Read-only compatible feature flags.
    pub read_only_compatible_feature_flags: u64,

    /// Incompatible feature flags.
    pub incompatible_feature_flags: u64,

    /// Container identifier.
    pub container_identifier: Uuid,

    /// Checkpoint descriptor area.
    pub checkpoint_descriptor_area: ApfsBlockRange,

    /// Object map block number.
    pub object_map_block_number: u64,

    /// Volume object identifiers.
    pub volume_object_identifiers: Vec<u64>,

    /// Fusion set identifier.
    pub fusion_set_identifier: Uuid,

    /// Key bag area.
    pub key_bag_area: ApfsBlockRange,
}

impl ApfsContainerSuperblock {
    /// Creates a new superblock.
    pub fn new() -> Self {
        Self {
            object_header: ApfsObjectHeader::new(),
            block_size: 0,
            number_of_blocks: 0,
            feature_flags: 0,
            read_only_compatible_feature_flags: 0,
            incompatible_feature_flags: 0,
            container_identifier: Uuid::new(),
            checkpoint_descriptor_area: ApfsBlockRange::new(),
            object_map_block_number: 0,
            volume_object_identifiers: Vec::new(),
            fusion_set_identifier: Uuid::new(),
            key_bag_area: ApfsBlockRange::new(),
        }
    }

    /// Reads the superblock from a buffer.
    pub fn read_data(&mut self, data: &[u8]) -> Result<(), ErrorTrace> {
        if data.len() < 4096 {
            return Err(keramics_core::error_trace_new!("Unsupported data size"));
        }
        if &data[32..36] != APFS_CONTAINER_SUPERBLOCK_SIGNATURE {
            return Err(keramics_core::error_trace_new!("Unsupported signature"));
        }
        match self.object_header.read_data(&data) {
            Ok(_) => {}
            Err(mut error) => {
                keramics_core::error_trace_add_frame!(error, "Unable to read object header");
                return Err(error);
            }
        }
        if self.object_header.object_type != 0x80000001 {
            return Err(keramics_core::error_trace_new!("Unsupported object type"));
        }
        if self.object_header.object_subtype != 0x00000000 {
            return Err(keramics_core::error_trace_new!(
                "Unsupported object subtype"
            ));
        }
        let calculated_checksum: u64 = ApfsObjectChecksum::calculate(&data[8..4096]);

        if self.object_header.checksum != calculated_checksum {
            return Err(keramics_core::error_trace_new!(format!(
                "Mismatch between stored: 0x{:016x} and calculated: 0x{:016x} checksums",
                self.object_header.checksum, calculated_checksum
            )));
        }
        let maximum_number_of_volumes: u32 = bytes_to_u32_le!(data, 180);

        if maximum_number_of_volumes > 100 {
            return Err(keramics_core::error_trace_new!(
                "Unsupported maximum number of volumes"
            ));
        }
        self.block_size = bytes_to_u32_le!(data, 36);
        self.number_of_blocks = bytes_to_u64_le!(data, 40);
        self.feature_flags = bytes_to_u64_le!(data, 48);
        self.read_only_compatible_feature_flags = bytes_to_u64_le!(data, 56);
        self.incompatible_feature_flags = bytes_to_u64_le!(data, 64);
        self.container_identifier = Uuid::from_be_bytes(&data[72..88]);

        self.checkpoint_descriptor_area.number_of_blocks = bytes_to_u32_le!(data, 104) as u64;
        self.checkpoint_descriptor_area.block_number = bytes_to_u64_le!(data, 112);
        self.object_map_block_number = bytes_to_u64_le!(data, 160);

        for data_offset in (184..984).step_by(8) {
            let volume_object_identifier: u64 = bytes_to_u64_le!(data, data_offset);
            if volume_object_identifier != 0 {
                self.volume_object_identifiers
                    .push(volume_object_identifier);
            }
        }
        self.fusion_set_identifier = Uuid::from_be_bytes(&data[1280..1296]);

        match self.key_bag_area.read_data(&data[1296..]) {
            Ok(_) => {}
            Err(mut error) => {
                keramics_core::error_trace_add_frame!(
                    error,
                    "Unable to read key bag area block range"
                );
                return Err(error);
            }
        }
        Ok(())
    }
}

