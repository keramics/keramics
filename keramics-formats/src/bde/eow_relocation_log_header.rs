use keramics_core::ErrorTrace;
use keramics_layout_map::LayoutMap;
use keramics_types::{bytes_to_u16_le, bytes_to_u32_le};

#[derive(LayoutMap)]
#[layout_map(
    structure(
        byte_order = "little",
        field(name = "signature", data_type = "[u8; 10]", format = "hex"),
        field(name = "unknown1", data_type = "u16"),
        field(name = "number_of_entries", data_type = "u16"),
        field(name = "logical_sector_size", data_type = "u32"),
        field(name = "volume_size", data_type = "u64"),
        field(name = "relocation_block_size", data_type = "u32"),
        field(name = "relocation_log_entry_size", data_type = "u32"),
        field(name = "unknown6", data_type = "u32"),
        field(name = "unknown7", data_type = "u32"),
        field(name = "volume_region_offset", data_type = "u64", format = "hex"),
    ),
    methods("debug_read_data")
)]
/// BitLocker Drive Encryption (BDE) Encrypt-on-Write (EOW) relocation log header.
pub struct BdeEowRelocationLogHeader {
    /// Number of entries.
    pub number_of_entries: u16,

    /// Relocation log entry size.
    pub entry_size: u32,
}

impl BdeEowRelocationLogHeader {
    /// Creates a new Encrypt-on-Write (EOW) relocation log header.
    pub fn new() -> Self {
        Self {
            number_of_entries: 0,
            entry_size: 0,
        }
    }

    /// Reads the Encrypt-on-Write (EOW) relocation log header from a buffer.
    pub fn read_data(&mut self, data: &[u8]) -> Result<(), ErrorTrace> {
        let data_size: usize = data.len();

        if data_size < 60 {
            return Err(keramics_core::error_trace_new!("Unsupported data size"));
        }
        if &data[0..10] != b"OLRDHEVF2\x00" {
            return Err(keramics_core::error_trace_new!("Unsupported signature"));
        }
        self.number_of_entries = bytes_to_u16_le!(data, 12);
        self.entry_size = bytes_to_u32_le!(data, 30);

        Ok(())
    }
}

