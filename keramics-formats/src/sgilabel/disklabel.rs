use keramics_core::ErrorTrace;
use keramics_layout_map::LayoutMap;

use super::constants::*;
use super::partition_entry::SgiDiskLabelPartitionEntry;

#[cfg(feature = "debug-trace")]
use super::device_parameters::SgiDeviceParameters;

#[cfg(feature = "debug-trace")]
use super::volume_descriptor::SgiDiskLabelVolumeDescriptor;

#[derive(LayoutMap)]
#[layout_map(
    structure(
        byte_order = "big",
        field(name = "signature1", data_type = "[u8; 4]", format = "hex"),
        field(name = "root_partition_number", data_type = "u16"),
        field(name = "swap_partition_number", data_type = "u16"),
        field(name = "boot_name", data_type = "ByteString<16>"),
        field(
            name = "device_parameters",
            data_type = "Struct<SgiDeviceParameters; 48>"
        ),
        field(
            name = "volume_descriptors",
            data_type = "[Struct<SgiDiskLabelVolumeDescriptor; 16>; 15]"
        ),
        field(
            name = "partition_entries",
            data_type = "[Struct<SgiDiskLabelPartitionEntry; 12>; 16]"
        ),
        field(name = "checksum", data_type = "u32"),
        field(name = "unknown2", data_type = "[u8; 4]"),
    ),
    methods("debug_read_data", "read_at_position")
)]
/// SGI disklabel (sgilabel) disklabel.
pub struct SgiDiskLabel {
    /// The partition entries.
    pub entries: Vec<SgiDiskLabelPartitionEntry>,
}

impl SgiDiskLabel {
    /// Creates a new disklabel.
    pub fn new() -> Self {
        Self {
            entries: Vec::new(),
        }
    }

    /// Reads the disklabel from a buffer.
    pub fn read_data(&mut self, data: &[u8]) -> Result<(), ErrorTrace> {
        if data.len() < 512 {
            return Err(keramics_core::error_trace_new!("Unsupported data size"));
        }
        if &data[0..4] != SGI_DISKLABEL_SIGNATURE {
            return Err(keramics_core::error_trace_new!("Unsupported signature"));
        }
        for (entry_index, data_offset) in (312..504).step_by(12).enumerate() {
            keramics_core::debug_trace_structure!(SgiDiskLabelPartitionEntry::debug_read_data(
                &data[data_offset..]
            ));
            let mut partition_entry: SgiDiskLabelPartitionEntry = SgiDiskLabelPartitionEntry::new();

            match partition_entry.read_data(&data[data_offset..]) {
                Ok(_) => {}
                Err(mut error) => {
                    keramics_core::error_trace_add_frame!(
                        error,
                        format!("Unable to read partition entry: {}", entry_index)
                    );
                    return Err(error);
                }
            }
            // Ignore empty, volume header and full volume partition entries.
            if partition_entry.number_of_blocks != 0
                && partition_entry.partition_type != 0
                && partition_entry.partition_type != 6
            {
                partition_entry.entry_index = entry_index as u8;

                self.entries.push(partition_entry);
            }
        }
        Ok(())
    }
}

