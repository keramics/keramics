use crate::block_stream::BlockStream;

use super::block_reader::SparseBundleBlockReader;

/// Mac OS sparse bundle (.sparsebundle) block stream.
pub type SparseBundleBlockStream = BlockStream<SparseBundleBlockReader>;

#[cfg(test)]
