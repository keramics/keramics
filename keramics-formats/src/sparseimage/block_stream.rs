    use crate::sparseimage::block_range::{SparseImageBlockRange, SparseImageBlockRangeType};
    use crate::tests::get_test_data_path;

    fn get_block_stream() -> Result<SparseImageBlockStream, ErrorTrace> {
        let test_path_string: String = get_test_data_path("sparseimage/hfsplus.sparseimage");
        let path_buf: PathBuf = PathBuf::from(test_path_string.as_str());
        let data_stream: DataStreamReference = open_os_data_stream(&path_buf)?;

        let block_ranges: Vec<SparseImageBlockRange> = vec![
            SparseImageBlockRange {
                logical_offset: 0,
                physical_band_number: 0,
                number_of_bands: 1,
                range_type: SparseImageBlockRangeType::InFile,
            },
            SparseImageBlockRange {
                logical_offset: 1048576,
                physical_band_number: 2,
                number_of_bands: 1,
                range_type: SparseImageBlockRangeType::InFile,
            },
            SparseImageBlockRange {
                logical_offset: 2097152,
                physical_band_number: 3,
                number_of_bands: 1,
                range_type: SparseImageBlockRangeType::InFile,
            },
            SparseImageBlockRange {
                logical_offset: 3145728,
                physical_band_number: 1,
                number_of_bands: 1,
                range_type: SparseImageBlockRangeType::InFile,
            },
        ];
        Ok(SparseImageBlockStream::new(SparseImageBlockReader::new(
            &data_stream,
            1048576,
            &block_ranges,
            4194304,
        )))
    }

    #[test]
    fn test_get_offset() -> Result<(), ErrorTrace> {
        let mut block_stream: SparseImageBlockStream = get_block_stream()?;

        block_stream.seek(SeekFrom::Start(1024))?;

        let offset: u64 = block_stream.get_offset()?;
        assert_eq!(offset, 1024);

        Ok(())
    }

    #[test]
    fn test_get_size() -> Result<(), ErrorTrace> {
        let mut block_stream: SparseImageBlockStream = get_block_stream()?;

        let size: u64 = block_stream.get_size()?;
        assert_eq!(size, 4194304);

        Ok(())
    }

    #[test]
    fn test_seek_from_start() -> Result<(), ErrorTrace> {
        let mut block_stream: SparseImageBlockStream = get_block_stream()?;

        let offset: u64 = block_stream.seek(SeekFrom::Start(1024))?;
        assert_eq!(offset, 1024);

        Ok(())
    }

    #[test]
    fn test_seek_from_end() -> Result<(), ErrorTrace> {
        let mut block_stream: SparseImageBlockStream = get_block_stream()?;
        let size: u64 = block_stream.get_size()?;

        let offset: u64 = block_stream.seek(SeekFrom::End(-512))?;
        assert_eq!(offset, size - 512);

        Ok(())
    }

    #[test]
    fn test_seek_from_current() -> Result<(), ErrorTrace> {
        let mut block_stream: SparseImageBlockStream = get_block_stream()?;

        let offset = block_stream.seek(SeekFrom::Start(1024))?;
        assert_eq!(offset, 1024);

        let offset: u64 = block_stream.seek(SeekFrom::Current(-512))?;
        assert_eq!(offset, 512);

        Ok(())
    }

    #[test]
    fn test_seek_before_zero() -> Result<(), ErrorTrace> {
        let mut block_stream: SparseImageBlockStream = get_block_stream()?;

        let result: Result<u64, ErrorTrace> = block_stream.seek(SeekFrom::Current(-512));
        assert!(result.is_err());

        Ok(())
    }

    #[test]
    fn test_seek_beyond_size() -> Result<(), ErrorTrace> {
        let mut block_stream: SparseImageBlockStream = get_block_stream()?;
        let size: u64 = block_stream.get_size()?;

        let offset: u64 = block_stream.seek(SeekFrom::End(512))?;
        assert_eq!(offset, size + 512);

        Ok(())
    }

