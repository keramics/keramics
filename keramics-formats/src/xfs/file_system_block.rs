use std::io::SeekFrom;

use keramics_core::{DataStreamReference, ErrorTrace};
use keramics_types::bytes_to_u16_be;

use super::file_system_block_header_v1::XfsFileSystemBlockHeaderV1;
use super::file_system_block_header_v3::XfsFileSystemBlockHeaderV3;

/// X File System (XFS) file system block.
pub struct XfsFileSystemBlock {
    /// Signature.
    pub signature: u16,

    /// Data.
    pub data: Vec<u8>,
}

impl XfsFileSystemBlock {
    /// Creates a new file system block.
    pub fn new() -> Self {
        Self {
            signature: 0,
            data: Vec::new(),
        }
    }

    /// Reads the file system block from a buffer.
    fn read_data(&mut self, data: &[u8]) -> Result<(), ErrorTrace> {
        let data_size: usize = data.len();

        if data_size < 10 {
            return Err(keramics_core::error_trace_new!("Unsupported data size"));
        }
        self.signature = bytes_to_u16_be!(data, 8);

        if self.signature == 0xfbee || self.signature == 0xfebe || self.signature == 0xfeeb {
            keramics_core::debug_trace_structure!(XfsFileSystemBlockHeaderV1::debug_read_data(
                &data
            ));
        } else if self.signature == 0x3bee || self.signature == 0x3ebe {
            keramics_core::debug_trace_structure!(XfsFileSystemBlockHeaderV3::debug_read_data(
                &data
            ));
        } else {
            return Err(keramics_core::error_trace_new!(format!(
                "Unsupported signature: 0x{:04x}",
                self.signature
            )));
        }
        Ok(())
    }

    /// Reads the file system block from a specific position in a data stream.
    pub fn read_at_position(
        &mut self,
        data_stream: &DataStreamReference,
        block_size: u32,
        position: SeekFrom,
    ) -> Result<(), ErrorTrace> {
        let mut data: Vec<u8> = vec![0; block_size as usize];

        let offset: u64 =
            keramics_core::data_stream_read_exact_at_position!(data_stream, &mut data, position);

        keramics_core::debug_trace_data!("XfsFileSystemBlock", offset, &data, block_size);

        match self.read_data(&data) {
            Ok(_) => {}
            Err(mut error) => {
                keramics_core::error_trace_add_frame!(
                    error,
                    format!(
                        "Unable to read file system block data at offset: {} (0x{:08x})",
                        offset, offset
                    )
                );
                return Err(error);
            }
        }
        self.data = data;

        Ok(())
    }
}

