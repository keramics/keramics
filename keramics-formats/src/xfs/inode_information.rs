use keramics_core::ErrorTrace;
use keramics_layout_map::LayoutMap;
use keramics_types::bytes_to_u32_be;

use super::constants::*;

#[derive(LayoutMap)]
#[layout_map(
    structure(
        byte_order = "big",
        field(name = "signature", data_type = "ByteString<4>"),
        field(name = "format_version", data_type = "u32"),
        field(name = "sequence_number", data_type = "u32"),
        field(name = "unknown1", data_type = "[u8; 4]"),
        field(name = "number_of_inodes", data_type = "u32"),
        field(name = "inode_btree_root_block_number", data_type = "u32"),
        field(name = "inode_btree_depth", data_type = "u32"),
        field(name = "number_of_unused_inodes", data_type = "u32"),
        field(name = "last_allocated_chunk", data_type = "u32"),
        field(name = "unknown2", data_type = "[u8; 4]"),
        field(name = "unlinked_hash_table", data_type = "[u32; 64]"),
        field(name = "block_type_identifier", data_type = "Uuid"),
        field(name = "checksum", data_type = "u32", format = "hex"),
        field(name = "unknown3", data_type = "[u8; 4]"),
        field(name = "log_sequence_number", data_type = "u64"),
        field(name = "free_inode_btree_root_block_number", data_type = "u32"),
        field(name = "free_inode_btree_depth", data_type = "u32"),
        field(name = "unknown4", data_type = "[u8; 4]"),
        field(name = "unknown5", data_type = "[u8; 4]"),
        field(name = "unknown6", data_type = "[u8; 168]"),
    ),
    methods("debug_read_data", "read_at_position")
)]
/// X File System (XFS) inode information
pub struct XfsInodeInformation {
    /// Inode B-tree root block number.
    pub inode_btree_root_block_number: u32,
}

impl XfsInodeInformation {
    /// Creates a new inode information.
    pub fn new() -> Self {
        Self {
            inode_btree_root_block_number: 0,
        }
    }
    /// Reads the inode information from a buffer.
    pub fn read_data(&mut self, data: &[u8]) -> Result<(), ErrorTrace> {
        if data.len() < 512 {
            return Err(keramics_core::error_trace_new!("Unsupported data size"));
        }
        if &data[0..4] != XFS_INODE_INFORMATION_SIGNATURE {
            return Err(keramics_core::error_trace_new!("Unsupported signature"));
        }
        let format_version: u32 = bytes_to_u32_be!(data, 4);

        if format_version != 1 {
            return Err(keramics_core::error_trace_new!(format!(
                "Unsupported format version: {}",
                format_version
            )));
        }
        self.inode_btree_root_block_number = bytes_to_u32_be!(data, 20);

        Ok(())
    }
}

