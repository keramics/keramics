use std::collections::HashSet;
use std::io::SeekFrom;

use keramics_core::{DataStreamReference, ErrorTrace};

use super::store_block::VolsnapStoreBlock;

/// Volume Shadow Snapshot (volsnap) store bitmap range.
pub struct VolsnapStoreBitmapRange {
    /// Size.
    pub size: u64,

    /// Value to indicate the bit was set.
    pub is_set: bool,
}

impl VolsnapStoreBitmapRange {
    /// Creates a new bitmap range.
    pub fn new(start_offset: u64, end_offset: u64, is_set: bool) -> Self {
        Self {
            size: end_offset - start_offset,
            is_set,
        }
    }
}

/// Volume Shadow Snapshot (volsnap) store bitmap.
pub struct VolsnapStoreBitmap {
    /// Number of bytes a single bit represents.
    bytes_per_bit: u16,

    /// The ranges.
    pub ranges: Vec<VolsnapStoreBitmapRange>,
}

impl VolsnapStoreBitmap {
    /// Creates a new bitmap.
    pub fn new(bytes_per_bit: u16) -> Self {
        Self {
            bytes_per_bit,
            ranges: Vec::new(),
        }
    }

    /// Reads the bitmap from a buffer.
    pub fn read_data(&mut self, data: &[u8]) -> Result<(), ErrorTrace> {
        let mut offset: u64 = 0;
        let mut range_offset: u64 = 0;
        let mut range_bit_value: u8 = data[0] & 0x01;

        for byte_value in data.iter() {
            let mut bit_values: u8 = *byte_value;
            for _ in 0..8 {
                let bit_value: u8 = bit_values & 0x01;
                bit_values >>= 1;

                if bit_value != range_bit_value {
                    self.ranges.push(VolsnapStoreBitmapRange::new(
                        range_offset,
                        offset,
                        range_bit_value != 0,
                    ));
                    range_offset = offset;
                    range_bit_value = bit_value;
                }
                offset += self.bytes_per_bit as u64;
            }
        }
        self.ranges.push(VolsnapStoreBitmapRange::new(
            range_offset,
            offset,
            range_bit_value != 0,
        ));
        Ok(())
    }

    /// Reads the bitmap from a specific position in a data stream.
    pub fn read_at_offset(
        &mut self,
        data_stream: &DataStreamReference,
        mut offset: u64,
    ) -> Result<(), ErrorTrace> {
        let mut read_store_blocks: HashSet<u64> = HashSet::new();

        loop {
            if read_store_blocks.contains(&offset) {
                return Err(keramics_core::error_trace_new!(format!(
                    "Store block at offset: {} (0x{:08x}) already read",
                    offset, offset
                )));
            }
            let mut store_block: VolsnapStoreBlock = VolsnapStoreBlock::new();

            match store_block.read_at_position(data_stream, SeekFrom::Start(offset)) {
                Ok(_) => {}
                Err(mut error) => {
                    keramics_core::error_trace_add_frame!(
                        error,
                        format!(
                            "Unable to read store bitmap block at offset: {} (0x{:08x})",
                            offset, offset
                        ),
                    );
                    return Err(error);
                }
            }
            read_store_blocks.insert(offset);

            if store_block.block_type != 6 {
                return Err(keramics_core::error_trace_new!(
                    "Unsupported store bitmap block - unsupported block type",
                ));
            }
            if store_block.current_block_offset != offset {
                return Err(keramics_core::error_trace_new!(
                    "Unsupported store bitmap block - current block offset value out of bounds",
                ));
            }
            // TODO: track bitmap offset
            match self.read_data(&store_block.data[128..]) {
                Ok(_) => {}
                Err(mut error) => {
                    keramics_core::error_trace_add_frame!(error, "Unable to read bitmap");
                    return Err(error);
                }
            }
            if store_block.next_block_offset == 0 {
                break;
            }
            if !store_block.next_block_offset.is_multiple_of(16384) {
                return Err(keramics_core::error_trace_new!(
                    "Unsupported store bitmap block - next block offset value not a multiple of 16384",
                ));
            }
            offset = store_block.next_block_offset;
        }
        Ok(())
    }
}

