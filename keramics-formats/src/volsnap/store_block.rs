use std::io::SeekFrom;

use keramics_core::{DataStreamReference, ErrorTrace};

use super::store_block_header::VolsnapStoreBlockHeader;

/// Volume Shadow Snapshot (volsnap) store block.
pub struct VolsnapStoreBlock {
    /// Block type.
    pub block_type: u32,

    /// Current block offset.
    pub current_block_offset: u64,

    /// Next block offset.
    pub next_block_offset: u64,

    /// Store metadata size.
    pub store_metadata_size: u64,

    /// Data.
    pub data: Vec<u8>,
}

impl VolsnapStoreBlock {
    /// Creates a new store block.
    pub fn new() -> Self {
        Self {
            block_type: 0,
            current_block_offset: 0,
            next_block_offset: 0,
            store_metadata_size: 0,
            data: Vec::new(),
        }
    }

    /// Reads the store block from a buffer.
    fn read_data(&mut self, data: &[u8], offset: u64) -> Result<(), ErrorTrace> {
        let data_size: usize = data.len();

        keramics_core::debug_trace_data_and_structure!(
            "VolsnapStoreBlockHeader",
            offset,
            &data[0..128],
            128,
            VolsnapStoreBlockHeader::debug_read_data(data)
        );
        let mut block_header: VolsnapStoreBlockHeader = VolsnapStoreBlockHeader::new();

        match block_header.read_data(data) {
            Ok(_) => {}
            Err(mut error) => {
                keramics_core::error_trace_add_frame!(error, "Unable to read store block header");
                return Err(error);
            }
        }
        self.block_type = block_header.block_type;
        self.current_block_offset = block_header.current_block_offset;
        self.next_block_offset = block_header.next_block_offset;

        if self.block_type == 4 {
            self.store_metadata_size = block_header.store_metadata_size;
        }
        Ok(())
    }

    /// Reads the store block from a specific position in a data stream.
    pub fn read_at_position(
        &mut self,
        data_stream: &DataStreamReference,
        position: SeekFrom,
    ) -> Result<(), ErrorTrace> {
        let mut data: Vec<u8> = vec![0; 16384];

        let offset: u64 =
            keramics_core::data_stream_read_exact_at_position!(data_stream, &mut data, position);

        match self.read_data(&data, offset) {
            Ok(_) => {}
            Err(mut error) => {
                keramics_core::error_trace_add_frame!(
                    error,
                    format!(
                        "Unable to read store block at offset: {} (0x{:08x})",
                        offset, offset
                    )
                );
                return Err(error);
            }
        }
        self.data = data;

        Ok(())
    }
}

