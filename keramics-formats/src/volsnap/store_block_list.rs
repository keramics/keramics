use std::collections::HashSet;
use std::io::SeekFrom;

use keramics_core::{DataStreamReference, ErrorTrace};

use super::block_descriptor::VolsnapBlockDescriptor;
use super::store_block::VolsnapStoreBlock;

/// Volume Shadow Snapshot (volsnap) store block list.
pub struct VolsnapStoreBlockList {
    /// Block descriptors.
    pub block_descriptors: Vec<VolsnapBlockDescriptor>,
}

impl VolsnapStoreBlockList {
    /// Creates a new block list.
    pub fn new() -> Self {
        Self {
            block_descriptors: Vec::new(),
        }
    }

    /// Reads the block list from a specific position in a data stream.
    pub fn read_at_offset(
        &mut self,
        data_stream: &DataStreamReference,
        mut offset: u64,
    ) -> Result<(), ErrorTrace> {
        let mut read_store_blocks: HashSet<u64> = HashSet::new();

        loop {
            if read_store_blocks.contains(&offset) {
                return Err(keramics_core::error_trace_new!(format!(
                    "Store block at offset: {} (0x{:08x}) already read",
                    offset, offset
                )));
            }
            let mut store_block: VolsnapStoreBlock = VolsnapStoreBlock::new();

            match store_block.read_at_position(data_stream, SeekFrom::Start(offset)) {
                Ok(_) => {}
                Err(mut error) => {
                    keramics_core::error_trace_add_frame!(
                        error,
                        format!(
                            "Unable to read store block list block at offset: {} (0x{:08x})",
                            offset, offset
                        ),
                    );
                    return Err(error);
                }
            }
            read_store_blocks.insert(offset);

            if store_block.block_type != 3 {
                return Err(keramics_core::error_trace_new!(
                    "Unsupported store block list block - unsupported block type",
                ));
            }
            if store_block.current_block_offset != offset {
                return Err(keramics_core::error_trace_new!(
                    "Unsupported store block list block - current block offset value out of bounds",
                ));
            }
            let data_size: usize = store_block.data.len();

            for data_offset in (128..data_size).step_by(32) {
                let data_end_offset: usize = data_offset + 32;

                if store_block.data[data_offset..data_end_offset] == [0; 32] {
                    break;
                }
                keramics_core::debug_trace_data_and_structure!(
                    "VolsnapBlockDescriptor",
                    offset + (data_offset as u64),
                    &store_block.data[data_offset..data_end_offset],
                    32,
                    VolsnapBlockDescriptor::debug_read_data(&store_block.data[data_offset..])
                );
                let mut block_descriptor: VolsnapBlockDescriptor = VolsnapBlockDescriptor::new();

                match block_descriptor.read_data(&store_block.data[data_offset..]) {
                    Ok(_) => {}
                    Err(mut error) => {
                        keramics_core::error_trace_add_frame!(
                            error,
                            "Unable to read block descriptor"
                        );
                        return Err(error);
                    }
                }
                self.block_descriptors.push(block_descriptor);
            }
            if store_block.next_block_offset == 0 {
                break;
            }
            if !store_block.next_block_offset.is_multiple_of(16384) {
                return Err(keramics_core::error_trace_new!(
                    "Unsupported store block list block - next block offset value not a multiple of 16384",
                ));
            }
            offset = store_block.next_block_offset;
        }
        Ok(())
    }
}

