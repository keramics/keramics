    #[test]
    fn test_read_data() -> Result<(), ErrorTrace> {
        let test_data: Vec<u8> = get_test_data();

        let mut test_struct = LuksVolumeHeaderV1::new();
        test_struct.read_data(&test_data)?;

        assert_eq!(test_struct.encryption_method, ByteString::from("aes"));
        assert_eq!(test_struct.encryption_mode, ByteString::from("cbc-plain"));
        assert_eq!(test_struct.hashing_method, ByteString::from("sha1"));
        assert_eq!(test_struct.encrypted_data_start_sector, 4096);
        assert_eq!(test_struct.key_size, 32);
        assert_eq!(test_struct.validation_hash, &test_data[112..132]);
        assert_eq!(test_struct.salt, &test_data[132..164]);
        assert_eq!(test_struct.number_of_iterations, 717220);
        assert_eq!(
            test_struct.volume_identifier,
            ByteString::from("05ea4190-f887-4dde-9f73-3b5c47179a13")
        );
        Ok(())
    }

