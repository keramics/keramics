#[derive(LayoutMap)]
#[layout_map(
    structure(
        byte_order = "big",
        field(name = "signature", data_type = "[u8; 6]", format = "hex"),
        field(name = "format_version", data_type = "u16"),
        field(name = "metadata_area_size", data_type = "u64"),
        field(name = "sequence_identifier", data_type = "u64"),
        field(name = "volume_label", data_type = "ByteString<48>"),
        field(name = "metadata_checksum_method", data_type = "ByteString<32>"),
        field(name = "salt", data_type = "[u8; 64]"),
        field(name = "volume_identifier", data_type = "ByteString<40>"),
        field(name = "subsystem", data_type = "ByteString<48>"),
        field(name = "header_offset", data_type = "u64"),
        field(name = "unknown1", data_type = "[u8; 184]"),
        field(name = "metadata_checksum", data_type = "[u8; 64]"),
        field(name = "unknown2", data_type = "[u8; 3584]"),
    ),
    methods("debug_read_data")
)]
/// Linux Unified Key Setup (LUKS) Disk Encryption volume header version 2.
pub struct LuksVolumeHeaderV2 {
    /// Metadata area size.
    pub metadata_area_size: u64,

    /// Volume label.
    pub volume_label: ByteString,

    /// Volume identifier.
    pub volume_identifier: ByteString,
}

impl LuksVolumeHeaderV2 {
    /// Creates a new volume header.
    pub fn new() -> Self {
        Self {
            metadata_area_size: 0,
            volume_label: ByteString::new(),
            volume_identifier: ByteString::new(),
        }
    }

    /// Reads the volume header from a buffer.
    pub fn read_data(&mut self, data: &[u8]) -> Result<(), ErrorTrace> {
        if data.len() < 4096 {
            return Err(keramics_core::error_trace_new!("Unsupported data size"));
        }
        if &data[0..6] != LUKS_VOLUME_HEADER_SIGNATURE {
            return Err(keramics_core::error_trace_new!("Unsupported signature"));
        }
        if &data[6..8] != &[0x00, 0x02] {
            return Err(keramics_core::error_trace_new!(
                "Unsupported format version"
            ));
        }
        self.metadata_area_size = bytes_to_u64_be!(data, 8);
        self.volume_label.read_data(&data[24..72]);
        self.volume_identifier.read_data(&data[168..208]);

        Ok(())
    }
}

