use keramics_core::ErrorTrace;
use keramics_layout_map::LayoutMap;
use keramics_types::bytes_to_u32_le;

use super::constants::*;
use super::raw_location_descriptor::LinuxLvmRawLocationDescriptor;

/// Linux Logical Volume Manager (LVM) metadata area header.
#[derive(LayoutMap)]
#[layout_map(
    structure(
        byte_order = "little",
        field(name = "checksum", data_type = "u32", format = "hex"),
        field(name = "signature", data_type = "ByteString<16>"),
        field(name = "format_version", data_type = "u32"),
        field(name = "area_offset", data_type = "u64", format = "hex"),
        field(name = "area_size", data_type = "u64"),
        field(
            name = "location_descriptors",
            data_type = "[Struct<LinuxLvmRawLocationDescriptor; 24>; 4]"
        ),
        field(name = "unknown1", data_type = "[u8; 376]"),
    ),
    methods("debug_read_data", "read_at_position")
)]
pub struct LinuxLvmMetadataAreaHeader {
    /// Checksum.
    pub checksum: u32,

    /// Format version.
    pub format_version: u32,

    /// Location descriptors.
    pub location_descriptors: Vec<LinuxLvmRawLocationDescriptor>,
}

impl LinuxLvmMetadataAreaHeader {
    /// Creates a new metadata area header.
    pub fn new() -> Self {
        Self {
            checksum: 0,
            format_version: 0,
            location_descriptors: Vec::new(),
        }
    }

    /// Reads the metadata area header from a buffer.
    pub fn read_data(&mut self, data: &[u8]) -> Result<(), ErrorTrace> {
        if data.len() < 512 {
            return Err(keramics_core::error_trace_new!("Unsupported data size"));
        }
        if &data[4..20] != LINUX_LVM_METADATA_AREA_SIGNATURE {
            return Err(keramics_core::error_trace_new!("Unsupported signature"));
        }
        self.checksum = bytes_to_u32_le!(data, 0);
        self.format_version = bytes_to_u32_le!(data, 20);

        for (descriptor_index, chunk) in data[40..136].chunks_exact(24).enumerate() {
            if chunk == &[0; 24] {
                break;
            }
            let mut raw_location_descriptor: LinuxLvmRawLocationDescriptor =
                LinuxLvmRawLocationDescriptor::new();

            match raw_location_descriptor.read_data(chunk) {
                Ok(_) => {}
                Err(mut error) => {
                    keramics_core::error_trace_add_frame!(
                        error,
                        format!(
                            "Unable to read raw location descriptor: {}",
                            descriptor_index
                        ),
                    );
                    return Err(error);
                }
            }
            if raw_location_descriptor.flags & 0x00000001 == 0 {
                self.location_descriptors.push(raw_location_descriptor);
            }
        }
        Ok(())
    }
}

