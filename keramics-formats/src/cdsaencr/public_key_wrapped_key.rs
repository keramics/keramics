use keramics_core::ErrorTrace;
use keramics_layout_map::LayoutMap;
use keramics_types::bytes_to_u32_be;

#[derive(LayoutMap)]
#[layout_map(
    structure(
        byte_order = "big",
        field(name = "hash_size", data_type = "u32"),
        field(name = "hash", data_type = "[u8; 20]", format = "hex"),
        field(name = "uknown1", data_type = "u32"),
        field(name = "uknown2", data_type = "u32"),
        field(name = "uknown3", data_type = "u32"),
        field(name = "uknown4", data_type = "u32"),
        field(name = "uknown5", data_type = "u32"),
        field(name = "uknown6", data_type = "u32"),
        field(name = "uknown7", data_type = "u32"),
        field(name = "uknown8", data_type = "[u8; 256]", format = "hex"),
        field(name = "uknown9", data_type = "[u8; 256]", format = "hex"),
    ),
    methods("debug_read_data")
)]
/// Mac OS Encrypted Encoding (cdsaencr) public wrapped key.
pub struct CdsaEncrPublicKeyWrappedKey {
    /// Key derivation method.
    pub key_derivation_method: u32,
}

impl CdsaEncrPublicKeyWrappedKey {
    /// Creates a new public key wrapped key.
    pub fn new() -> Self {
        Self {
            key_derivation_method: 0,
        }
    }

    /// Reads the public key wrapped key from a buffer.
    pub fn read_data(&mut self, data: &[u8]) -> Result<(), ErrorTrace> {
        if data.len() < 360 {
            return Err(keramics_core::error_trace_new!("Unsupported data size"));
        }
        self.key_derivation_method = bytes_to_u32_be!(data, 0);

        Ok(())
    }
}

