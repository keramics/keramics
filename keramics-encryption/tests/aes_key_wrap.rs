#[test]
fn test_unwrap() -> Result<(), ErrorTrace> {
    for (test_number, test_vector) in AES_KEY_WRAP_TEST_VECTORS.iter().enumerate() {
        let key_bit_size: usize = test_vector.key.len() * 8;

        let mut aes_key_wrap_context: AesKeyWrapContext = AesKeyWrapContext::new();
        aes_key_wrap_context.set_key(&test_vector.key)?;

        let data_size: usize = test_vector.ciphertext.len();
        let mut data: Vec<u8> = vec![0; data_size];

        aes_key_wrap_context.unwrap(&test_vector.ciphertext, &mut data)?;
        assert_eq!(
            &data[0..8],
            &[0xa6; 8],
            "intialization vector mismatch with {} bits test vector: {}",
            key_bit_size,
            test_number + 1
        );
        assert_eq!(
            &data[8..],
            test_vector.plaintext,
            "plaintext mismatch with {} bits test vector: {}",
            key_bit_size,
            test_number + 1
        );
    }
    Ok(())
}

#[test]
fn test_encrypt_ccm() -> Result<(), ErrorTrace> {
    for (test_number, test_vector) in AES_KEY_WRAP_TEST_VECTORS.iter().enumerate() {
        let key_bit_size: usize = test_vector.key.len() * 8;

        let mut aes_key_wrap_context: AesKeyWrapContext = AesKeyWrapContext::new();
        aes_key_wrap_context.set_key(&test_vector.key)?;

        let encrypted_data_size: usize = test_vector.ciphertext.len();
        let mut encrypted_data: Vec<u8> = vec![0; encrypted_data_size];

        aes_key_wrap_context.wrap(&[0xa6; 8], &test_vector.plaintext, &mut encrypted_data)?;
        assert_eq!(
            &encrypted_data,
            test_vector.ciphertext,
            "ciphertext mismatch with {} bits test vector: {}",
            key_bit_size,
            test_number + 1
        );
    }
    Ok(())
}
