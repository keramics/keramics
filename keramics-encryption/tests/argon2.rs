#[test]
fn test_derive_key() -> Result<(), ErrorTrace> {
    for (test_number, test_vector) in ARGON2_TEST_VECTORS.iter().enumerate() {
        let mut argon2_context: Argon2Context = Argon2Context::new(
            test_vector.argon2_type,
            test_vector.salt,
            test_vector.number_of_iterations,
            test_vector.memory_size_kib,
            test_vector.parallelism,
        );
        argon2_context.set_secret(test_vector.secret);
        argon2_context.set_associated_data(test_vector.associated_data);

        let tag_size: usize = test_vector.tag.len();
        let mut derived_key: Vec<u8> = vec![0; tag_size];
        argon2_context.derive_key(test_vector.password, &mut derived_key)?;

        assert_eq!(
            derived_key,
            test_vector.tag,
            "Argon2 ({:?}) mismatch for test vector: {}",
            test_vector.argon2_type,
            test_number + 1
        );
    }
    Ok(())
}
