#[test]
fn test_decrypt_ccm() -> Result<(), ErrorTrace> {
    for (test_number, test_vector) in CCM_TEST_VECTORS.iter().enumerate() {
        let key_bit_size: usize = test_vector.key.len() * 8;

        let mut aes_context: AesCcmContext =
            AesCcmContext::new(&test_vector.nonce, &test_vector.associated_data);
        aes_context.set_key(&test_vector.key)?;

        let data_size: usize = test_vector.plaintext.len();
        let mut data: Vec<u8> = vec![0; data_size];

        let tag_size: usize = test_vector.tag.len();
        let mut tag: Vec<u8> = vec![0; tag_size];

        aes_context.decrypt(&test_vector.ciphertext, &mut data, &mut tag)?;
        assert_eq!(
            &data,
            test_vector.plaintext,
            "plaintext mismatch with {} bits test vector: {}",
            key_bit_size,
            test_number + 1
        );
        let mut validation_check: u8 = 0;

        for data_offset in 0..tag_size {
            validation_check |= test_vector.tag[data_offset] ^ tag[data_offset];
        }
        assert_eq!(
            validation_check,
            0,
            "validation failture for {} bits test vector: {}",
            key_bit_size,
            test_number + 1
        );
    }
    Ok(())
}

#[test]
fn test_encrypt_ccm() -> Result<(), ErrorTrace> {
    for (test_number, test_vector) in CCM_TEST_VECTORS.iter().enumerate() {
        let key_bit_size: usize = test_vector.key.len() * 8;

        let mut aes_context: AesCcmContext =
            AesCcmContext::new(&test_vector.nonce, &test_vector.associated_data);
        aes_context.set_key(&test_vector.key)?;

        let encrypted_data_size: usize = test_vector.ciphertext.len();
        let mut encrypted_data: Vec<u8> = vec![0; encrypted_data_size];

        let tag_size: usize = test_vector.tag.len();
        let mut tag: Vec<u8> = vec![0; tag_size];

        aes_context.encrypt(&test_vector.plaintext, &mut encrypted_data, &mut tag)?;
        assert_eq!(
            &encrypted_data,
            &test_vector.ciphertext,
            "ciphertext mismatch with {} bits test vector: {}",
            key_bit_size,
            test_number + 1
        );
        assert_eq!(
            &tag,
            &test_vector.tag,
            "tag mismatch with {} bits test vector: {}",
            key_bit_size,
            test_number + 1
        );
    }
    Ok(())
}
